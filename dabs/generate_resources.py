"""Codegen: config/tables.json -> Databricks Asset Bundle resource YAML.

The DABs path is driven by the SAME single source of truth as Terraform's `for_each` and the
deploy loop (ADR 0004): the repo-root `config/tables.json`. DABs YAML cannot loop a JSON list
into N resources, so this generator emits, per table, one `postgres_synced_tables` resource — a
transparent, diffable artifact rather than a hidden mutator (ADR 0006 / D2/D3). Adding a table
stays a one-line `config/tables.json` edit.

The app role is deliberately NOT emitted as a `postgres_roles` DAB resource. An admin creates each
app role once (`CREATE ROLE <app_role> NOLOGIN`), and the migration checks `pg_roles` for it (see
`dabs/render_ddl.py role_guard_sql`) rather than creating or owning it. Keeping the role outside the
bundle means `bundle destroy` can never drop the role out from under grants that consumers still
hold, and the two migration paths (DABs renderer + Liquibase) check the same admin-managed role with
no DAB resource to drift against. The role name still flows through to the migration via
`migration_targets` below.

Schema mapping (field names verified against `databricks bundle schema`, CLI v1.14.1):

  config/tables.json field    -> bundle location
  --------------------------      -----------------
  name                        -> synced-table resource key <name>
  synced_table_id             -> postgres_synced_tables.<name>.synced_table_id   (required)
                                 postgres_synced_tables.<name>.new_pipeline_spec.storage_catalog
                                   (DERIVED: 1st dotted part of synced_table_id)
                                 postgres_synced_tables.<name>.new_pipeline_spec.storage_schema
                                   (DERIVED: 2nd dotted part of synced_table_id)
  source_table_full_name      -> postgres_synced_tables.<name>.source_table_full_name
  primary_key_columns         -> postgres_synced_tables.<name>.primary_key_columns
  scheduling_policy (optional)-> postgres_synced_tables.<name>.scheduling_policy
                                 (default SNAPSHOT; enum CONTINUOUS|TRIGGERED|SNAPSHOT). The
                                 synced-table CREATE API rejects a missing policy, so it always emits.
  app_role, app_schema,       -> variables.migration_targets.default[]  (see note; the migration job
    index_columns                checks the role + applies grants/indexes/view)

`postgres_synced_tables` declares `additionalProperties: false` in the bundle schema, so there is NO
native resource field for a synced table's index columns, its target schema, or its app role. Those
are consumed by the migration job (which checks that the admin-created role exists and renders + applies the grants, indexes
and consumer view), so they are carried as a bundle `variables` complex default (`migration_targets`)
— a bundle-legal location that `databricks bundle validate` accepts and the job task can read.
This keeps index columns "carried through" in full (no fixed-count truncation) without inventing
a resource field that the CLI would reject.

Environment-specific placement is left as bundle variable references so no customer/workspace-specific
value is committed: the synced table's `postgres_database` uses `${var.lakebase_database}` and its
`branch` uses `${var.lakebase_branch}`, so a target sets the branch once and the synced table follows
it onto the right Lakebase branch (dev/prod placement stays separated, and an ephemeral-branch test
can isolate). Those variables are declared in the bundle's `databricks.yml` targets.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

# The table-name and view-name uniqueness seams + load_tables live in dabs/render_ddl.py (the
# single home shared with the Liquibase path). This generator does not emit views, but it shares
# config/tables.json with the migration job that DOES, so it enforces the same cross-entry
# constraints at generation time.
from dabs.render_ddl import (
    load_tables,
    validate_table_names_unique,
    validate_view_names_unique,
)

# Bundle variable references for environment-specific values (declared in databricks.yml targets).
# Kept as references — never literal workspace/branch values — so nothing customer-specific is committed.
BRANCH_VAR = "${var.lakebase_branch}"
DATABASE_VAR = "${var.lakebase_database}"

# Scheduling policy for a synced table's underlying pipeline. Enum verified against
# `databricks bundle schema`, CLI v1.14.1
# (postgres.SyncedTableSyncedTableSpecSyncedTableSchedulingPolicy).
VALID_SCHEDULING_POLICIES = ("CONTINUOUS", "TRIGGERED", "SNAPSHOT")
DEFAULT_SCHEDULING_POLICY = "SNAPSHOT"

_GENERATED_HEADER = (
    "# GENERATED by dabs/generate_resources.py from config/tables.json — DO NOT EDIT BY HAND.\n"
    "# Re-run the generator after editing config/tables.json (single source of truth, ADR 0004).\n"
)
# A file counts as generated only when its FIRST line is this marker. A file that merely quotes the
# marker further down, or a symlink, is not ours and is never removed.
_GENERATED_MARKER = _GENERATED_HEADER.splitlines()[0]


def _is_generated(path: Path) -> bool:
    """True for a regular file (never a symlink) whose first line is this generator's marker."""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        with path.open(encoding="utf-8") as fh:
            return fh.readline().rstrip("\n") == _GENERATED_MARKER
    except (OSError, UnicodeDecodeError):
        return False


def _scheduling_policy(table: dict) -> str:
    """Resolve the synced table's `scheduling_policy`.

    Defaults to SNAPSHOT; an OPTIONAL `scheduling_policy` field on the config row overrides it
    (backward-compatible: absent -> SNAPSHOT). Rejects any value outside the bundle-schema enum so
    codegen never emits a policy the CLI would refuse. The synced-table CREATE API rejects a
    missing/None policy ('Unsupported scheduling policy: None'), so this field must always emit.

    NOTE: TRIGGERED and CONTINUOUS require Change Data Feed on the Delta source
    (delta.enableChangeDataFeed = true); SNAPSHOT does not.
    """
    policy = table.get("scheduling_policy", DEFAULT_SCHEDULING_POLICY)
    if policy not in VALID_SCHEDULING_POLICIES:
        raise ValueError(
            f"scheduling_policy {policy!r} for table {table.get('name')!r} is not one of "
            f"{VALID_SCHEDULING_POLICIES} (bundle-schema enum)"
        )
    return policy


def _new_pipeline_spec(table: dict) -> dict[str, str]:
    """Derive `new_pipeline_spec.storage_catalog` / `storage_schema` from the synced_table_id.

    The pipeline created for the synced table stores its intermediate files (checkpoints, event
    logs) in the synced table's OWN catalog and schema — the 1st and 2nd dotted parts of the
    3-part `catalog.schema.table` identifier — matching the deployed reference Terraform. Sub-field
    names verified against `databricks bundle schema`, CLI v1.14.1 (postgres.NewPipelineSpec):
    storage_catalog, storage_schema.
    """
    parts = table["synced_table_id"].split(".")
    if len(parts) < 3:
        raise ValueError(
            f"synced_table_id {table['synced_table_id']!r} for table {table.get('name')!r} "
            "must be a 3-part catalog.schema.table identifier"
        )
    return {"storage_catalog": parts[0], "storage_schema": parts[1]}


def build_synced_table_resource(table: dict) -> dict[str, Any]:
    """One `postgres_synced_tables` resource body for a table row."""
    return {
        "synced_table_id": table["synced_table_id"],
        "source_table_full_name": table["source_table_full_name"],
        "primary_key_columns": list(table["primary_key_columns"]),
        "postgres_database": DATABASE_VAR,
        "branch": BRANCH_VAR,
        "scheduling_policy": _scheduling_policy(table),
        "new_pipeline_spec": _new_pipeline_spec(table),
        "create_database_objects_if_missing": True,
    }


def build_migration_target(table: dict) -> dict[str, Any]:
    """Per-table migration metadata the migration job consumes (schema + full index column list)."""
    return {
        "name": table["name"],
        "app_schema": table["app_schema"],
        "app_role": table["app_role"],
        "index_columns": list(table["index_columns"]),
    }


def build_bundle_fragments(tables: list[dict]) -> dict[str, dict]:
    """Pure function: tables list -> {filename: bundle-fragment dict}.

    Emits one per-table resource file (`<name>.yml`) carrying that table's synced table, plus a
    single `migration_targets.yml` carrying the per-table migration metadata (app role, schema,
    index columns) as a bundle complex variable. The app role is intentionally NOT a
    `postgres_roles` DAB resource — an admin creates it once and the migration job checks for it —
    so it travels only via `migration_targets`. Fully deterministic — no timestamps or ids — so re-running is a clean diff.
    """
    validate_table_names_unique(tables)  # cross-entry: two entries must not share a table name
    validate_view_names_unique(tables)  # cross-entry: two entries must not resolve to one view
    fragments: dict[str, dict] = {}
    targets: list[dict] = []
    for table in tables:
        name = table["name"]
        fragments[f"{name}.yml"] = {
            "resources": {
                "postgres_synced_tables": {name: build_synced_table_resource(table)},
            }
        }
        targets.append(build_migration_target(table))

    fragments["migration_targets.yml"] = {
        "variables": {
            "migration_targets": {
                "type": "complex",
                "description": (
                    "Per-table migration metadata (target schema + index columns) generated from "
                    "config/tables.json and consumed by the migration job. Index columns "
                    "have no native postgres_synced_tables field, so they are carried here."
                ),
                "default": targets,
            }
        }
    }
    return fragments


def _dump(fragment: dict) -> str:
    """Serialize a bundle fragment to deterministic, block-style YAML with a generated header."""
    body = yaml.safe_dump(fragment, default_flow_style=False, sort_keys=False)
    return _GENERATED_HEADER + body


def stale_resources(tables: list[dict], out_dir: str | Path) -> tuple[list[Path], list[Path]]:
    """The `*.yml` files in `out_dir` that no config row generates, split in two:
    (generated files that are now stale, files this generator did not write).
    Write mode removes only the first list; `--check` reports both and removes nothing."""
    expected = set(build_bundle_fragments(tables))
    out = Path(out_dir)
    stale: list[Path] = []
    foreign: list[Path] = []
    if out.is_dir():
        for path in sorted(out.glob("*.yml")):
            if path.name in expected:
                continue
            (stale if _is_generated(path) else foreign).append(path)
    return stale, foreign


def write_resources(tables: list[dict], out_dir: str | Path) -> list[Path]:
    """Generate and write all bundle-fragment files to `out_dir`, then remove the generated files of
    entries that are no longer in the config (a renamed or deleted entry would otherwise leave its old
    resource behind, and `bundle deploy` would apply it). Files this generator did not write are never
    removed. Returns the paths written."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    # Computed first: an invalid config raises here, before anything is written or removed.
    stale, _foreign = stale_resources(tables, out)
    written: list[Path] = []
    for filename, fragment in build_bundle_fragments(tables).items():
        path = out / filename
        path.write_text(_dump(fragment))
        written.append(path)
    for path in stale:
        path.unlink()
    return written


def check_drift(config_path: str | Path, resources_dir: str | Path) -> list[str]:
    """Verify committed resource files in `resources_dir` byte-match a FRESH generation from
    `config_path`. Returns a list of human-readable drift descriptions; empty list == no drift.

    This is the anti-drift guard: `write_resources` is never called, so nothing is mutated. Three
    ways a committed tree can drift from the single source of truth are all reported —
      - a committed file whose bytes differ from the freshly generated content (stale/hand-edited),
      - an expected file that is missing from the committed tree,
      - a committed .yml that no config row generates (orphan/leftover).
    """
    expected = {fn: _dump(fragment) for fn, fragment in build_bundle_fragments(load_tables(config_path)).items()}
    resources = Path(resources_dir)
    committed = {p.name: p for p in resources.glob("*.yml")}

    problems: list[str] = []
    for fn, content in expected.items():
        if fn not in committed:
            problems.append(f"missing committed resource: {fn} (expected from config, not present)")
        elif committed[fn].read_text() != content:
            problems.append(f"drift in {fn}: committed bytes differ from fresh generation")
    for fn in committed:
        if fn not in expected:
            problems.append(f"unexpected committed resource: {fn} (no config row generates it)")
    return problems


def main(argv: list[str] | None = None) -> int:
    repo_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--config",
        default=str(repo_root / "config" / "tables.json"),
        help="Path to the single-source-of-truth tables.json (default: repo config/tables.json).",
    )
    parser.add_argument(
        "--out",
        default=str(Path(__file__).resolve().parent / "resources"),
        help="Output directory for generated bundle resource YAML (default: dabs/resources).",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify-only: confirm the committed resources in --out byte-match a fresh generation "
             "from --config, exit non-zero on any drift. Writes nothing (for CI / the offline gate).",
    )
    args = parser.parse_args(argv)

    if args.check:
        problems = check_drift(args.config, args.out)
        if problems:
            for p in problems:
                print(f"DRIFT: {p}", file=sys.stderr)
            print(
                f"ERROR: committed resources in {args.out} are stale vs {args.config} "
                f"({len(problems)} issue(s)). Re-run codegen and commit dabs/resources/*.yml.",
                file=sys.stderr,
            )
            return 1
        print(f"no drift: committed resources in {args.out} match a fresh generation from {args.config}")
        return 0

    tables = load_tables(args.config)
    stale, foreign = stale_resources(tables, args.out)
    written = write_resources(tables, args.out)
    for path in written:
        print(f"wrote {path}")
    for path in stale:
        print(f"removed stale generated file {path} (no entry in {args.config} generates it)")
    for path in foreign:
        print(
            f"kept {path}: this generator did not write it, so it is not removed; "
            "`--check` flags it, so delete it by hand if it is stale"
        )
    print(f"generated {len(written)} file(s) for {len(tables)} table(s) from {args.config}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
